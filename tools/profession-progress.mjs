import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const targets = read('registry/profession-targets.json');
const registry = read('registry/professions.json');
const maturity = read('registry/maturity.json');
const policy = read('registry/coverage-policy.json');
const targetCount = Object.values(targets.domains).reduce((n, items) => n + items.length, 0);
const constructionByStatus = {};
for (const p of registry.professions) constructionByStatus[p.status] = (constructionByStatus[p.status] ?? 0) + 1;
const evidenceByStatus = {};
for (const p of maturity.records) evidenceByStatus[p.status] = (evidenceByStatus[p.status] ?? 0) + 1;
const usable = maturity.records.filter(p => policy.usable_statuses.includes(p.status)).length;
console.log(JSON.stringify({targetCount, registeredPackages: registry.professions.length, usablePackages: usable, usableGoal: policy.target_profession_count, constructionByStatus, evidenceByStatus}, null, 2));
